"""
Patient endpoints.

Every handler takes the current doctor from `require_doctor` and passes it to the
service. `doctor_id` is never a body field or a query parameter — there is no
schema anywhere that accepts one — so a client cannot claim to be a different
doctor. It arrives only from the authenticated request context (§8.12).
"""

from __future__ import annotations

from typing import List, Optional
from uuid import UUID

import psycopg
from fastapi import APIRouter, Depends, Query, Response, status

from app.api.deps import CurrentDoctor, get_db, require_doctor
from app.db.repositories import patients as patients_repo
from app.schemas.common import ErrorResponse
from app.schemas.follow_ups import FollowUpSummary
from app.schemas.insights import InsightSummary
from app.schemas.patients import PatientCreate, PatientOut, PatientUpdate
from app.schemas.timeline import TimelineOut, TimelineVisit
from app.schemas.visits import VisitOut
from app.services import patient_service

# require_doctor depends on require_auth, so listing it here keeps both gates on
# every route in this router even if a handler forgets to name the dependency.
router = APIRouter(prefix="/patients", tags=["patients"],
                   dependencies=[Depends(require_doctor)])


@router.post(
    "",
    response_model=PatientOut,
    status_code=status.HTTP_201_CREATED,
    responses={401: {"model": ErrorResponse, "description": "No doctor identity"},
               409: {"model": ErrorResponse,
                     "description": "A probable duplicate already exists"}},
    summary="Register a patient",
)
def add_patient(
    payload: PatientCreate,
    conn: psycopg.Connection = Depends(get_db),
    doctor: CurrentDoctor = Depends(require_doctor),
) -> PatientOut:
    """Register a patient under the signed-in doctor and return the record.

    Identity is anchored on `external_id`, generated by the database when not
    supplied. Sharing a name and date of birth with an existing patient **of the
    same doctor** returns 409 with that patient's id; resubmit with
    `allow_duplicate: true` if they really are a different person.

    Sharing a name and date of birth with *another doctor's* patient is not a
    conflict and never was one clinically — see §8.10.
    """
    patient = patient_service.add_patient(
        conn,
        doctor.doctor_id,
        first_name=payload.first_name,
        last_name=payload.last_name,
        date_of_birth=payload.date_of_birth,
        gender=payload.gender,
        phone=payload.phone,
        email=str(payload.email) if payload.email else None,
        external_id=payload.external_id,
        allow_duplicate=payload.allow_duplicate,
    )
    return PatientOut.model_validate(patient)


@router.get("", response_model=List[PatientOut], summary="List or search patients")
def list_patients(
    response: Response,
    q: Optional[str] = Query(default=None,
                             description="Match on name, clinic number or phone"),
    sort: str = Query(default="name", pattern="^(name|created_desc)$"),
    limit: int = Query(default=100, ge=1, le=500),
    offset: int = Query(default=0, ge=0),
    conn: psycopg.Connection = Depends(get_db),
    doctor: CurrentDoctor = Depends(require_doctor),
) -> List[PatientOut]:
    """The signed-in doctor's patients, optionally filtered by a search term.

    The total is returned in `X-Total-Count` rather than wrapping the array in an
    envelope, because the header is additive and changing the body shape would
    break existing callers. The count is scoped the same way as the list, so it
    reports what this doctor can actually see.
    """
    rows = patients_repo.list_all(conn, doctor.doctor_id, q=q, sort=sort,
                                 limit=limit, offset=offset)
    response.headers["X-Total-Count"] = str(
        patients_repo.count_all(conn, doctor.doctor_id, q=q))
    return [PatientOut.model_validate(r) for r in rows]


@router.get(
    "/{patient_id}",
    response_model=PatientOut,
    responses={401: {"model": ErrorResponse},
               404: {"model": ErrorResponse}},
    summary="Get one patient",
)
def get_patient(
    patient_id: UUID,
    conn: psycopg.Connection = Depends(get_db),
    doctor: CurrentDoctor = Depends(require_doctor),
) -> PatientOut:
    """One patient.

    **404, not 403**, when the id belongs to another doctor's patient. A 403 would
    confirm the id exists, which discloses that some other doctor has a record
    under it; an unknown id and someone else's id are deliberately the same
    answer.
    """
    return PatientOut.model_validate(
        patient_service.get_patient(conn, doctor.doctor_id, str(patient_id)))


@router.patch(
    "/{patient_id}",
    response_model=PatientOut,
    responses={401: {"model": ErrorResponse},
               404: {"model": ErrorResponse},
               422: {"model": ErrorResponse}},
    summary="Correct a patient's demographics",
)
def update_patient(
    patient_id: UUID,
    payload: PatientUpdate,
    conn: psycopg.Connection = Depends(get_db),
    doctor: CurrentDoctor = Depends(require_doctor),
) -> PatientOut:
    """Update demographics. `external_id` is not editable: it is the identity key.

    Neither is `doctor_id` — it is not in `PatientUpdate` at all. Moving a patient
    between doctors is a transfer of clinical custody that would carry every visit,
    insight and follow-up with it, not a demographics correction.

    `date_of_birth` matters most, because it is the basis of `age_at_visit` on
    every one of the patient's visits.
    """
    updated = patient_service.update_patient(
        conn, doctor.doctor_id, str(patient_id),
        payload.model_dump(exclude_unset=True, mode="json"),
    )
    return PatientOut.model_validate(updated)


@router.get(
    "/{patient_id}/timeline",
    response_model=TimelineOut,
    responses={401: {"model": ErrorResponse},
               404: {"model": ErrorResponse}},
    summary="A patient's whole record",
)
def get_timeline(
    patient_id: UUID,
    conn: psycopg.Connection = Depends(get_db),
    doctor: CurrentDoctor = Depends(require_doctor),
) -> TimelineOut:
    """The patient plus every visit, newest first, each with its brief and
    follow-up attached.

    Summary fields only: `insights_json` is 20-30 KB per visit, so the full
    record stays on `GET /visits/{visit_id}/insights`.

    The single highest-value read in the API — one request returns a patient's
    entire clinical history. All four underlying queries are doctor-scoped, not
    just the patient lookup.
    """
    data = patient_service.build_timeline(conn, doctor.doctor_id, str(patient_id))
    return TimelineOut(
        patient=PatientOut.model_validate(data["patient"]),
        visits=[_timeline_visit(entry) for entry in data["visits"]],
    )


def _timeline_visit(entry: dict) -> TimelineVisit:
    """Combine a visit row with its optional insight and follow-up."""
    visit = VisitOut.model_validate(entry["visit"])
    insight = (InsightSummary.model_validate(entry["insight"])
               if entry["insight"] else None)
    follow_up = (FollowUpSummary.model_validate(entry["follow_up"])
                 if entry["follow_up"] else None)
    return TimelineVisit(**visit.model_dump(), insight=insight, follow_up=follow_up)
