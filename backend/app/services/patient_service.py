"""Patient registration, scoped to one doctor."""

from __future__ import annotations

import logging
from datetime import date
from typing import Any, Dict, Optional

import psycopg

from app.core.errors import DuplicatePatientError, NotFoundError, ValidationError
from app.db.models import PatientRow
from app.db.repositories import follow_ups as follow_ups_repo
from app.db.repositories import insights as insights_repo
from app.db.repositories import patients as patients_repo
from app.db.repositories import visits as visits_repo
from app.db.tenancy import DoctorScope
from app.domain.identity import normalise_phone

logger = logging.getLogger(__name__)


def add_patient(
    conn: psycopg.Connection,
    scope: DoctorScope,
    first_name: str,
    last_name: Optional[str],
    date_of_birth: date,
    gender: Optional[str] = None,
    phone: Optional[str] = None,
    email: Optional[str] = None,
    external_id: Optional[str] = None,
    allow_duplicate: bool = False,
) -> PatientRow:
    """Register a patient owned by the scoped doctor.

    external_id is the hard identity key and is generated by the database when
    not supplied. Name plus date of birth is only used to flag a *probable*
    duplicate, which the caller resolves by reusing the returned patient or
    resubmitting with allow_duplicate=True. Blocking outright would eventually
    reject a legitimate patient, since demographics are not a reliable key.

    Both uniqueness rules behave differently across doctors, and the difference is
    the point (§8.10):

      external_id  globally unique, because it is system-generated from one
                   sequence. A collision is reported without naming the holder.
      name + DOB   unique *within one doctor's patients only*. Two doctors having
                   a patient with the same name and date of birth is ordinary,
                   and must not be a conflict.
    """
    if external_id:
        # Scoped lookup first, so the doctor's own duplicate gets the helpful
        # answer including the id they can reuse.
        mine = patients_repo.get_by_external_id(conn, scope, external_id)
        if mine:
            raise DuplicatePatientError(
                f"A patient already exists with external_id {external_id!r}.",
                details={"existing_patient_id": mine.patient_id,
                         "match_reason": "external_id"},
            )
        # The constraint is global, so the insert would still fail if another
        # doctor holds this number. Report that it is taken and stop there: the
        # holder's patient_id and name are not ours to disclose, and knowing a
        # clinic number exists elsewhere is itself information about another
        # practice's records. In practice this is unreachable for generated ids —
        # it only fires when a caller supplies external_id by hand.
        if patients_repo.external_id_taken(conn, external_id):
            raise DuplicatePatientError(
                f"The external_id {external_id!r} is already in use. Clinic "
                f"numbers are unique across the whole system; omit external_id "
                f"to have one generated.",
                details={"match_reason": "external_id_unavailable"},
            )

    if not allow_duplicate:
        probable = patients_repo.find_probable_duplicate(
            conn, scope, first_name, last_name, date_of_birth)
        if probable:
            raise DuplicatePatientError(
                f"A patient with the same name and date of birth already exists "
                f"({probable.external_id}). Resubmit with allow_duplicate=true if "
                f"this is a different person.",
                details={"existing_patient_id": probable.patient_id,
                         "existing_external_id": probable.external_id,
                         "match_reason": "name_and_date_of_birth"},
            )

    patient = patients_repo.create(
        conn,
        scope,
        first_name=first_name.strip(),
        last_name=(last_name or "").strip() or None,
        date_of_birth=date_of_birth,
        gender=(gender or "").strip().lower() or None,
        phone=normalise_phone(phone),
        email=(email or "").strip() or None,
        external_id=external_id,
    )
    logger.info("Registered patient %s (%s) for doctor %s",
                patient.external_id, patient.patient_id, patient.doctor_id)
    return patient


def get_patient(conn: psycopg.Connection, scope: DoctorScope,
                patient_id: str) -> PatientRow:
    """One of the scoped doctor's patients.

    404 — not 403 — when the row exists but belongs to another doctor. A 403 would
    confirm the id is real, which tells the caller another doctor has a patient
    under it; the repository returns None for both cases so this function cannot
    tell them apart even if it wanted to.
    """
    patient = patients_repo.get(conn, scope, patient_id)
    if patient is None:
        raise NotFoundError(f"No patient with id {patient_id}.")
    return patient


def update_patient(
    conn: psycopg.Connection,
    scope: DoctorScope,
    patient_id: str,
    changes: Dict[str, Any],
) -> PatientRow:
    """Correct a patient's demographics.

    Matters most for `date_of_birth`: it is the basis of `age_at_visit` on every
    visit, so a wrong one silently misreports the patient's age across their
    whole history.
    """
    get_patient(conn, scope, patient_id)  # 404 if unknown or another doctor's

    cleaned: Dict[str, Any] = {}
    for field, value in changes.items():
        if field == "phone":
            cleaned[field] = normalise_phone(value)
        elif field == "gender":
            cleaned[field] = (value or "").strip().lower() or None
        elif field in ("first_name", "last_name", "email"):
            cleaned[field] = (value or "").strip() or None
        else:
            cleaned[field] = value

    # first_name is NOT NULL, so an explicit blank must not wipe it.
    if "first_name" in cleaned and not cleaned["first_name"]:
        raise ValidationError("first_name cannot be empty.")

    updated = patients_repo.update(conn, scope, patient_id, cleaned)
    logger.info("Updated patient %s: %s", patient_id, ", ".join(cleaned))
    return updated  # type: ignore[return-value]


def build_timeline(conn: psycopg.Connection, scope: DoctorScope,
                   patient_id: str) -> Dict[str, Any]:
    """A patient plus every visit, each with its brief and follow-up.

    One query per table rather than one per visit: the visits, their insights and
    their follow-ups are fetched in three reads and stitched in memory.

    All four reads carry the same scope. The insight and follow-up reads would
    look safe unscoped, since their visit ids come from an already-scoped visit
    list — but that is a property of today's call order, not of the queries, and it
    is the kind of reasoning that stops holding after a refactor nobody thinks to
    re-audit.
    """
    patient = get_patient(conn, scope, patient_id)
    visits = visits_repo.list_visits(conn, scope, patient_id=patient_id,
                                     sort="date_desc")

    visit_ids = [v.visit_id for v in visits]
    insights = {i.visit_id: i for i in
                insights_repo.list_for_visits(conn, scope, visit_ids)}
    follow_ups = {f.source_visit_id: f for f in
                  follow_ups_repo.list_for_visits(conn, scope, visit_ids)}

    return {
        "patient": patient,
        "visits": [{"visit": v,
                    "insight": insights.get(v.visit_id),
                    "follow_up": follow_ups.get(v.visit_id)}
                   for v in visits],
    }
